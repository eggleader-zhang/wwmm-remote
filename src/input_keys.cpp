int nativeKeyCode(DesktopOS os, quint8 usage)
{
    for (auto k : codes)
        if (k.usage == usage)
            return os == DesktopOS::macOS ? k.mac : k.win;
    return -1;
}

quint8 hidKey(DesktopOS os, int code)
{
    if (code >= 0)
        for (auto k : codes)
            if ((os == DesktopOS::macOS ? k.mac : k.win) == code)
                return k.usage;
    return 0;
}

quint8 modifierBit(quint8 usage)
{
    return usage >= 224 && usage <= 231 ? quint8(1u << (usage - 224)) : 0;
}
